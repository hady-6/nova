async function fetchPin(id) {
  const r = await fetch('https://widgets.pinterest.com/v3/pidgets/pins/info/?pin_ids=' + encodeURIComponent(id));
  if (!r.ok) throw new Error('network');
  const j = await r.json();
  const pin = j && j.data && j.data[0];
  if (!pin) throw new Error('notfound');
  const title = decodeEntities(String((pin.rich_metadata && pin.rich_metadata.title) || pin.description || t('pin_default'))).slice(0, 120);
  const list = pin.videos && pin.videos.video_list;
  if (list) {
    const variants = Object.entries(list)
      .filter(([, v]) => v && typeof v.url === 'string' && v.url.endsWith('.mp4'))
      .map(([key, v]) => ({
        key,
        label: key.replace(/^V_/, '').toLowerCase(),
        url: v.url,
        kind: 'video',
        width: v.width || 0,
        height: v.height || 0,
      }))
      .sort((a, b) => b.width - a.width);
    if (variants.length) return { id, title, variants, kind: 'pinterest' };
  }
  const imgs = pin.images;
  if (imgs) {
    const order = ['orig', '736x', '564x', '474x', '236x', '170x'];
    const variants = Object.entries(imgs)
      .filter(([, v]) => v && typeof v.url === 'string')
      .map(([key, v]) => ({ key, label: key === 'orig' ? 'original' : key, url: v.url, kind: 'image', width: v.width || 0, height: v.height || 0 }))
      .sort((a, b) => order.indexOf(a.key) - order.indexOf(b.key));
    if (variants.length) return { id, title, variants, kind: 'image' };
  }
  throw new Error('novideo');
}

async function fetchTikTok(url) {
  const r = await fetch('https://www.tikwm.com/api/?url=' + encodeURIComponent(url));
  if (!r.ok) throw new Error('network');
  const j = await r.json();
  if (!j || j.code !== 0 || !j.data) throw new Error('notfound');
  const d = j.data;
  const variants = [];
  if (d.hdplay) variants.push({ label: 'HD', url: d.hdplay, kind: 'video', width: 0, height: 0 });
  if (d.play) variants.push({ label: 'SD', url: d.play, kind: 'video', width: 0, height: 0 });
  if (d.music) variants.push({ label: 'audio', url: d.music, kind: 'audio', width: 0, height: 0 });
  (d.images || []).forEach((im, i) => variants.push({ label: (i + 1) + '', url: im, kind: 'image', width: 0, height: 0 }));
  if (!variants.length) throw new Error('novideo');
  const title = String(d.title || t('tt_default')).slice(0, 120);
  return { title, variants, kind: 'tiktok' };
}

async function fetchX(url) {
  const m = url.match(/(?:twitter\.com|x\.com)\/([^/?]+)\/status\/(\d+)/i);
  if (!m) throw new Error('bad');
  const r = await fetch('https://api.fxtwitter.com/' + m[1] + '/status/' + m[2]);
  if (!r.ok) throw new Error('network');
  const j = await r.json();
  const tw = j && j.tweet;
  if (!tw) throw new Error('notfound');
  const media = tw.media || {};
  const variants = [];
  (media.videos || []).forEach((v, i) => variants.push({ label: 'video' + (i ? ' ' + (i + 1) : ''), url: v.url, kind: 'video', width: v.width || 0, height: v.height || 0 }));
  (media.photos || []).forEach((p, i) => variants.push({ label: (i + 1) + '', url: p.url, kind: 'image', width: p.width || 0, height: p.height || 0 }));
  if (!variants.length) throw new Error('novideo');
  const title = decodeEntities(String(tw.text || t('x_default'))).slice(0, 120);
  return { title, variants, kind: 'x' };
}

async function go() {
  reset();
  let s = $('url').value.trim();
  if (!s && navigator.clipboard && navigator.clipboard.readText) {
    try {
      const c = (await navigator.clipboard.readText()).trim();
      if (c) { s = c; $('url').value = c; }
    } catch { /* إذن الحافظة مرفوض أو غير مدعوم - نكمّل بالسلوك العادي */ }
  }
  if (!s) return showError('bad');
  if (/(youtube\.com|youtu\.be)/i.test(s)) return showError('yt');
  const isShort = /(pin\.it|vt\.tiktok\.com|vm\.tiktok\.com)\//i.test(s);
  if (BACKEND) {
    const btn = $('go');
    btn.disabled = true;
    btn.querySelector('span').textContent = t('going');
    showModal('modal_analyzing');
    try {
      const r = await fetch(BACKEND + '/api/extract?url=' + encodeURIComponent(s));
      const d = await r.json();
      if (!r.ok || !d.media || !d.media.length) throw new Error(r.status === 404 ? 'notfound' : 'network');
      renderMedia({
        resolved: d.resolved_url || s,
        kind: d.media[0].kind,
        title: decodeEntities(String(d.title || '')),
        thumbnail: d.thumbnail || null,
        duration: d.duration || null,
        source: d.source || '',
        variants: d.media.map((m) => ({ url: m.url, label: m.quality, kind: m.kind, size: m.size, ext: m.ext })),
      });
      $('pin-result').hidden = false;
    } catch (e) {
      showError(['notfound', 'novideo'].includes(e.message) ? e.message : 'network');
    } finally {
      hideModal();
      btn.disabled = false;
      btn.querySelector('span').textContent = t('go');
    }
    return;
  }
  if (isShort) return showError('short');
  if (isDirectVideo(s)) {
    $('direct-result').hidden = false;
    $('direct-result').dataset.url = s;
    return;
  }
  const id = extractPinId(s);
  const isTt = /(tiktok\.com|vt\.tiktok\.com|vm\.tiktok\.com)/i.test(s);
  const isX = /(twitter\.com|x\.com)\/[^/?]+\/status\/\d+/i.test(s);
  if (!id && !isTt && !isX) return showError('bad');
  const btn = $('go');
  btn.disabled = true;
  btn.querySelector('span').textContent = t('going');
  try {
    const media = isTt ? await fetchTikTok(s) : isX ? await fetchX(s) : await fetchPin(id);
    renderMedia(media);
    $('pin-result').hidden = false;
  } catch (e) {
    showError(['notfound', 'novideo', 'network'].includes(e.message) ? e.message : 'network');
  } finally {
    btn.disabled = false;
    btn.querySelector('span').textContent = t('go');
  }
}

