function fmtSize(b) {
  if (b == null || !isFinite(b)) return '';
  const mb = b / 1048576;
  return mb >= 1 ? mb.toFixed(2) + ' MB' : Math.max(1, Math.round(b / 1024)) + ' KB';
}
function fmtDur(s) {
  if (!s || !isFinite(s)) return '';
  s = Math.round(s);
  return Math.floor(s / 60) + ':' + String(s % 60).padStart(2, '0');
}
